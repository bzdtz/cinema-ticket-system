-- 座位状态值拆分：影厅模板里的 1 -> -2
--
-- 背景：座位矩阵存在两个地方，但 1 有两种含义。
--   hall.hall_size      影厅布局模板，1 是影厅编辑器点出来的「损坏座位」
--   showtimes.seat      单场座位快照，建排片时整份拷贝模板，1 是「已售」
-- 于是每开一场新片，模板里的损坏座位都会被显示成已售，上座率也算错。
--
-- 现在的约定（前端三处已统一）：
--   0 可选   1 已售   -1 无座位(过道)   -2 损坏座位
-- 影厅编辑器不再能产出 1，所以只需要把模板里的历史 1 改成 -2。
--
-- showtimes.seat 不动：那是历史场次的快照，事后已无法区分哪些 1 是真卖出、
-- 哪些是从脏模板继承来的，改写历史比留着更危险（这批场次日期都在 2024 年，已播完）。
--
-- 执行前备份：.tools/hall-backup-before-seat-migration.sql

